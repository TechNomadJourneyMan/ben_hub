function t(str, vars = {}) {
  if (!str) return '';
  return String(str).replace(/\{(\w+)\}/g, (_, k) => vars[k] !== undefined ? vars[k] : `{${k}}`);
}

const LangContext = React.createContext({ lang: 'ru', T: TRANSLATIONS['ru'], setLang: () => {} });

function LangProvider({ children }) {
  const [lang, setLangState] = React.useState(() => {
    try { const s = localStorage.getItem('ben_lang'); if (s && TRANSLATIONS[s]) return s; } catch(e) {}
    const nav = (navigator.language || '').split('-')[0].toLowerCase();
    const map = { kk: 'kz', ky: 'kg', uk: 'uk', de: 'de', tr: 'tr', zh: 'zh', 'zh-hans': 'zh' };
    return (TRANSLATIONS[nav] && nav) || (map[nav] && TRANSLATIONS[map[nav]] && map[nav]) || 'ru';
  });
  const setLang = (code) => {
    setLangState(code);
    try { localStorage.setItem('ben_lang', code); } catch(e) {}
  };
  return React.createElement(LangContext.Provider, { value: { lang, T: TRANSLATIONS[lang], setLang, t } }, children);
}

function useLang() { return React.useContext(LangContext); }

function LangSwitcher() {
  const { lang, setLang } = useLang();
  const [open, setOpen] = React.useState(false);
  const ref = React.useRef(null);
  React.useEffect(() => {
    const fn = (e) => { if (ref.current && !ref.current.contains(e.target)) setOpen(false); };
    document.addEventListener('mousedown', fn);
    return () => document.removeEventListener('mousedown', fn);
  }, []);
  const current = LANGUAGES.find(l => l.code === lang) || LANGUAGES[0];
  return React.createElement('div', { ref, style: { position: 'relative' } },
    React.createElement('button', {
      onClick: () => setOpen(o => !o),
      style: { display: 'flex', alignItems: 'center', gap: 6, padding: '6px 12px', background: 'var(--bg-card)', border: '1px solid var(--border)', borderRadius: 'var(--r-md)', fontSize: 13, fontWeight: 700, color: 'var(--text-2)', cursor: 'pointer', transition: 'all .2s', fontFamily: 'inherit', whiteSpace: 'nowrap' }
    },
      React.createElement('span', { style: { fontSize: 11, background: 'var(--indigo)', color: '#fff', padding: '2px 5px', borderRadius: 4, fontFamily: 'monospace', letterSpacing: '.04em' } }, current.flag),
      React.createElement('span', null, current.label),
      React.createElement('svg', { width: 14, height: 14, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', strokeWidth: 2, strokeLinecap: 'round', strokeLinejoin: 'round', style: { transition: 'transform .2s', transform: open ? 'rotate(180deg)' : 'none' } },
        React.createElement('polyline', { points: '6 9 12 15 18 9' })
      )
    ),
    open && React.createElement('div', {
      style: { position: 'absolute', top: 'calc(100% + 6px)', right: 0, background: 'var(--bg-card)', border: '1px solid var(--border)', borderRadius: 'var(--r-lg)', boxShadow: 'var(--shadow)', overflow: 'hidden', minWidth: 160, zIndex: 300, animation: 'slideUp .2s ease' }
    },
      LANGUAGES.map(l => React.createElement('button', {
        key: l.code,
        onClick: () => { setLang(l.code); setOpen(false); },
        style: { display: 'flex', alignItems: 'center', gap: 10, width: '100%', padding: '10px 14px', background: l.code === lang ? 'var(--indigo-bg)' : 'transparent', border: 'none', borderBottom: '1px solid var(--border-2)', cursor: 'pointer', fontSize: 13, color: l.code === lang ? 'var(--text)' : 'var(--text-2)', fontWeight: l.code === lang ? 700 : 400, fontFamily: 'inherit', textAlign: 'left', transition: 'background .15s' }
      },
        React.createElement('span', { style: { fontSize: 10, background: l.code === lang ? 'var(--orange)' : 'var(--muted)', color: '#fff', padding: '2px 5px', borderRadius: 3, fontFamily: 'monospace', letterSpacing: '.04em', flexShrink: 0 } }, l.flag),
        l.label
      ))
    )
  );
}

